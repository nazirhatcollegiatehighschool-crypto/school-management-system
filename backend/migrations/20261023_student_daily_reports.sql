CREATE TABLE IF NOT EXISTS public.student_daily_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  class_id INTEGER NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
  teacher_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  report_date DATE NOT NULL,
  subject_name TEXT NOT NULL,
  homework_status TEXT NOT NULL CHECK (homework_status IN ('done','not_done')),
  learning_status TEXT NOT NULL CHECK (learning_status IN ('learned','partial','not_learned')),
  performance TEXT NOT NULL CHECK (performance IN ('good','average','poor')),
  uniform_brought BOOLEAN NOT NULL DEFAULT TRUE,
  note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (student_id, teacher_id, report_date, subject_name)
);

CREATE INDEX IF NOT EXISTS idx_student_daily_reports_student_date
  ON public.student_daily_reports (student_id, report_date DESC);

ALTER TABLE public.students
  ADD COLUMN IF NOT EXISTS receives_scholarship BOOLEAN NOT NULL DEFAULT FALSE;
