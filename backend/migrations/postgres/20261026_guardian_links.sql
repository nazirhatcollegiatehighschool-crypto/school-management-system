-- Guardian login and sibling approval require a stable ownership link table.
CREATE TABLE IF NOT EXISTS public.guardian_links (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guardian_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  student_id INTEGER NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  role VARCHAR(20) NOT NULL DEFAULT 'sibling'
    CHECK (role IN ('primary', 'sibling')),
  status VARCHAR(20) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'rejected')),
  requester_student_id INTEGER REFERENCES public.students(id) ON DELETE SET NULL,
  decided_by INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
  remark VARCHAR(255),
  requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  decided_at TIMESTAMPTZ,
  CONSTRAINT uq_guardian_links_guardian_student UNIQUE (guardian_id, student_id)
);

CREATE INDEX IF NOT EXISTS ix_guardian_links_student
  ON public.guardian_links (student_id);
CREATE INDEX IF NOT EXISTS ix_guardian_links_status
  ON public.guardian_links (status);
