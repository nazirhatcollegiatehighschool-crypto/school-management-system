-- Consolidated add-only schema for the profile, uniform-report, notification and
-- attendance-access workflows. Supersedes the 20261029_* preparation files.
-- Safe to rerun. No table or row is dropped; the only data updates normalize
-- legacy gender/status spellings and backfill the new one-time profile lock.
ALTER TABLE public.students
  ADD COLUMN IF NOT EXISTS guardian_profile_locked_at TIMESTAMPTZ DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS class10_start_year SMALLINT,
  ADD COLUMN IF NOT EXISTS is_irregular BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS teacher_dob DATE,
  ADD COLUMN IF NOT EXISTS teacher_address VARCHAR(255),
  ADD COLUMN IF NOT EXISTS teacher_blood_group VARCHAR(5),
  ADD COLUMN IF NOT EXISTS teacher_index_number VARCHAR(40),
  ADD COLUMN IF NOT EXISTS teacher_pns_number VARCHAR(40),
  ADD COLUMN IF NOT EXISTS teacher_degree VARCHAR(150),
  ADD COLUMN IF NOT EXISTS teacher_joining_date DATE;

ALTER TABLE public.notifications ADD COLUMN IF NOT EXISTS target_user_id INTEGER;
CREATE INDEX IF NOT EXISTS idx_notifications_target_user ON public.notifications(target_user_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_notifications_dedup ON public.notifications(dedup_key);

ALTER TABLE public.attendance_delegation ADD COLUMN IF NOT EXISTS expires_at_epoch BIGINT;
ALTER TABLE public.attendance_summary
  ADD COLUMN IF NOT EXISTS early_departure_with_leave INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS early_departure_no_leave INTEGER NOT NULL DEFAULT 0;
CREATE INDEX IF NOT EXISTS idx_attendance_delegation_scope
  ON public.attendance_delegation(class_id, date, session, granted_to);

CREATE TABLE IF NOT EXISTS public.attendance_access_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  class_id INTEGER NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
  class_teacher_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  requested_by INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  attendance_date DATE NOT NULL,
  session VARCHAR(20) NOT NULL,
  routine_slot_id INTEGER,
  status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected','expired')),
  expires_at_epoch BIGINT NOT NULL,
  decided_by INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
  decided_at TIMESTAMPTZ,
  delegation_id INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_att_access_inbox ON public.attendance_access_requests(class_teacher_id, status, expires_at_epoch);
CREATE INDEX IF NOT EXISTS idx_att_access_requester ON public.attendance_access_requests(requested_by, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_att_access_scope ON public.attendance_access_requests(class_id, attendance_date, session);

CREATE TABLE IF NOT EXISTS public.student_profile_edit_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  guardian_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  class_id INTEGER NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
  class_teacher_id INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
  reason VARCHAR(1000) NOT NULL,
  proposed_changes JSONB,
  status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','resolved','rejected')),
  reviewed_by INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
  reviewer_role VARCHAR(20),
  admin_note VARCHAR(1000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  reviewed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_student_profile_request_student ON public.student_profile_edit_requests(student_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_student_profile_request_teacher ON public.student_profile_edit_requests(class_teacher_id, status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.student_uniform_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  class_id INTEGER NOT NULL REFERENCES public.classes(id) ON DELETE CASCADE,
  teacher_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  report_date DATE NOT NULL,
  uniform_brought BOOLEAN NOT NULL,
  note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (student_id, report_date)
);
CREATE INDEX IF NOT EXISTS idx_student_uniform_reports_class_date
  ON public.student_uniform_reports(class_id, report_date DESC);

CREATE TABLE IF NOT EXISTS public.teacher_notification_reads (
  notification_id INTEGER NOT NULL REFERENCES public.notifications(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  read_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (notification_id, user_id)
);

-- Existing profiles that already contain every required field stay locked;
-- incomplete admissions remain open for the guardian's one-time completion.
UPDATE public.students
SET guardian_profile_locked_at = NOW()
WHERE guardian_profile_locked_at IS NULL
  AND NULLIF(TRIM(name), '') IS NOT NULL
  AND NULLIF(TRIM(religion), '') IS NOT NULL
  AND NULLIF(TRIM(guardian_name), '') IS NOT NULL
  AND NULLIF(TRIM(guardian_phone), '') IS NOT NULL
  AND NULLIF(TRIM(father_name), '') IS NOT NULL
  AND NULLIF(TRIM(mother_name), '') IS NOT NULL
  AND NULLIF(TRIM(address), '') IS NOT NULL
  AND NULLIF(TRIM(gender), '') IS NOT NULL;

UPDATE public.students
SET class10_start_year = COALESCE(class10_start_year,
  (SELECT substring(se.name from '([0-9]{4})')::smallint FROM public.sessions se WHERE se.id = students.session_id))
WHERE EXISTS (SELECT 1 FROM public.classes c WHERE c.id = students.class_id AND c.name ~ '(^|[^0-9])10([^0-9]|$)');

UPDATE public.students SET is_irregular = TRUE, status = 'active' WHERE status = 'irregular';
UPDATE public.students
SET gender = 'Female'
WHERE LOWER(TRIM(gender)) IN ('female', 'femal', 'femail', 'females');
