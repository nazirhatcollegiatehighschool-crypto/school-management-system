-- Production gap fix (2026-11-06): two tables are referenced by live routes but
-- were never created on the deployed database, so those features returned 500.
--   1. event_promotion_grace  -> per-event/class/subject grace choices, used by
--      result publishing (/api/results/.../publish) and the teacher/admin
--      promotion review screens.
--   2. marksheet_templates    -> GET/POST /api/admin/marksheet-templates.
-- Add-only: no existing table, column or row is touched.
CREATE TABLE IF NOT EXISTS event_promotion_grace (
  event_id INTEGER NOT NULL REFERENCES exam_events(id) ON DELETE CASCADE,
  class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  subject_id INTEGER NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  granted_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (event_id, class_id, subject_id)
);

CREATE INDEX IF NOT EXISTS ix_event_promotion_grace_class
  ON event_promotion_grace (class_id, event_id);

CREATE TABLE IF NOT EXISTS marksheet_templates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  is_default BOOLEAN NOT NULL DEFAULT false,
  layout_json JSONB,
  grading_scale_json JSONB,
  branding_json JSONB,
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_marksheet_templates_default
  ON marksheet_templates (is_default);
