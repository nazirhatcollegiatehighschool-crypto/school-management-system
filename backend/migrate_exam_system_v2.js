require('dotenv').config({ quiet: true });
const { Pool } = require('pg');
const p = new Pool({ connectionString: process.env.DATABASE_URL, ssl: { rejectUnauthorized: false }, connectionTimeoutMillis: 15000 });

async function addColumn(table, col, def) {
  await p.query(`ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS ${col} ${def}`);
}

(async () => {
  // ------------------------------------------------------------------
  // 1) exam_catalog — NCTB band rules + weightage engine (Q1, Q2)
  // ------------------------------------------------------------------
  await p.query(`
    CREATE TABLE IF NOT EXISTS exam_catalog (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      band VARCHAR(10) NOT NULL CHECK (band IN ('6-9','10','ssc')),
      exam_kind VARCHAR(20) NOT NULL,
      weight_pct NUMERIC(5,2) NOT NULL DEFAULT 0,
      is_promotion_source SMALLINT NOT NULL DEFAULT 0,
      sort_order INTEGER NOT NULL DEFAULT 0,
      updated_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      UNIQUE (band, exam_kind)
    )`);
  console.log('exam_catalog table ready');

  const seedCatalog = [
    ['6-9', 'ca',          20, 0, 1],
    ['6-9', 'half_yearly', 30, 0, 2],
    ['6-9', 'annual',      50, 1, 3],
    ['10',  'pretest',     30, 0, 1],
    ['10',  'test',        70, 1, 2],
    ['ssc', 'model_test', 100, 0, 1],
    ['ssc', 'test',        70, 1, 2],
  ];
  for (const [band, kind, pct, promo, ord] of seedCatalog) {
    await p.query(
      `INSERT INTO exam_catalog (band, exam_kind, weight_pct, is_promotion_source, sort_order)
       VALUES ($1,$2,$3,$4,$5) ON CONFLICT (band, exam_kind) DO NOTHING`,
      [band, kind, pct, promo, ord]
    );
  }
  console.log('exam_catalog seeded:', seedCatalog.length);

  // ------------------------------------------------------------------
  // 2) mandatory_pass — subject-level rules that grace cannot override (Q7)
  // ------------------------------------------------------------------
  await p.query(`
    CREATE TABLE IF NOT EXISTS mandatory_pass (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
      subject_id INTEGER NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      UNIQUE (class_id, subject_id)
    )`);
  console.log('mandatory_pass table ready');

  // Seed Bangla / English / Math for every class where those subjects exist.
  const seeded = await p.query(`
    INSERT INTO mandatory_pass (class_id, subject_id)
    SELECT DISTINCT s.class_id, s.id
      FROM subjects s
     WHERE s.class_id IN (SELECT id FROM classes WHERE name LIKE 'Class %')
       AND (s.name ILIKE 'Bangla%' OR s.name ILIKE 'English%' OR s.name ILIKE 'Math%' OR s.name ILIKE 'গণিত%' OR s.name ILIKE 'বাংলা%')
    ON CONFLICT (class_id, subject_id) DO NOTHING`);
  console.log('mandatory_pass seeded rows:', seeded.rowCount);

  // ------------------------------------------------------------------
  // 3) exams — workflow states (Q3, Q6)
  // ------------------------------------------------------------------
  await addColumn('exams', 'entry_status', `VARCHAR(20) NOT NULL DEFAULT 'draft'`);
  await addColumn('exams', 'submitted_at', 'TIMESTAMPTZ');
  await addColumn('exams', 'submitted_by', 'INTEGER REFERENCES users(id) ON DELETE SET NULL');
  await addColumn('exams', 'approved_at', 'TIMESTAMPTZ');
  await addColumn('exams', 'approved_by', 'INTEGER REFERENCES users(id) ON DELETE SET NULL');
  await addColumn('exams', 'reject_reason', 'TEXT');
  await p.query(`
    UPDATE exams SET entry_status = CASE WHEN status='published' THEN 'approved' ELSE 'draft' END
     WHERE entry_status IS NULL OR entry_status = ''`);
  await p.query(`
    CREATE INDEX IF NOT EXISTS ix_exams_entry_status ON exams (entry_status)`);
  console.log('exams workflow columns ready');

  // ------------------------------------------------------------------
  // 4) results — materialized marks + dual merit positions (Q9)
  // ------------------------------------------------------------------
  await addColumn('results', 'total_marks_obtained', 'NUMERIC(8,2) DEFAULT 0');
  await addColumn('results', 'total_marks_full', 'NUMERIC(8,2) DEFAULT 0');
  await addColumn('results', 'section_position', 'INTEGER');
  await addColumn('results', 'combined_position', 'INTEGER');
  await addColumn('results', 'section_size', 'INTEGER');
  await addColumn('results', 'combined_size', 'INTEGER');
  await addColumn('results', 'pass_all', 'SMALLINT DEFAULT 0');
  await p.query(`CREATE INDEX IF NOT EXISTS ix_results_student_exam ON results (student_id, exam_id)`);
  console.log('results columns ready');

  // ------------------------------------------------------------------
  // 5) promotion_runs / section_allocations (Q9 mechanic 2)
  // ------------------------------------------------------------------
  await p.query(`
    CREATE TABLE IF NOT EXISTS promotion_runs (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      event_id INTEGER NOT NULL REFERENCES exam_events(id) ON DELETE CASCADE,
      from_class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
      algorithm VARCHAR(30) NOT NULL DEFAULT 'round_robin',
      total_promoted INTEGER NOT NULL DEFAULT 0,
      sections_count INTEGER NOT NULL DEFAULT 0,
      status VARCHAR(20) NOT NULL DEFAULT 'draft'
             CHECK (status IN ('draft','balanced','rolled','executed')),
      executed_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
      executed_at TIMESTAMPTZ,
      notes TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      UNIQUE (event_id, from_class_id)
    )`);
  console.log('promotion_runs table ready');

  await p.query(`
    CREATE TABLE IF NOT EXISTS section_allocations (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      run_id INTEGER NOT NULL REFERENCES promotion_runs(id) ON DELETE CASCADE,
      student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
      from_class_id INTEGER NOT NULL,
      from_section VARCHAR(30),
      to_class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
      to_section VARCHAR(30) NOT NULL,
      combined_rank INTEGER NOT NULL,
      assigned_roll INTEGER NOT NULL,
      allocated_by VARCHAR(10) NOT NULL DEFAULT 'auto' CHECK (allocated_by IN ('auto','admin')),
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      UNIQUE (run_id, student_id)
    )`);
  await p.query(`CREATE INDEX IF NOT EXISTS ix_section_alloc_run ON section_allocations (run_id)`);
  console.log('section_allocations table ready');

  // ------------------------------------------------------------------
  // 6) group_selections / group_transfers / group_eligibility_rules (Q9 mechanic 3)
  // ------------------------------------------------------------------
  await p.query(`
    CREATE TABLE IF NOT EXISTS group_selections (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      run_id INTEGER REFERENCES promotion_runs(id) ON DELETE SET NULL,
      student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
      from_class_id INTEGER NOT NULL,
      to_group VARCHAR(30) NOT NULL,
      to_class_id INTEGER REFERENCES classes(id) ON DELETE SET NULL,
      eligible_groups TEXT[],
      base_score NUMERIC(8,2) DEFAULT 0,
      selected_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
      selected_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      status VARCHAR(20) NOT NULL DEFAULT 'confirmed' CHECK (status IN ('pending','confirmed')),
      UNIQUE (student_id, from_class_id)
    )`);
  console.log('group_selections table ready');

  await p.query(`
    CREATE TABLE IF NOT EXISTS group_transfers (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
      from_group VARCHAR(30) NOT NULL,
      to_group VARCHAR(30) NOT NULL,
      from_class_id INTEGER NOT NULL,
      to_class_id INTEGER NOT NULL,
      reason TEXT,
      previous_roll INTEGER,
      new_roll INTEGER,
      previous_combined_rank INTEGER,
      new_combined_rank INTEGER,
      executed_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
      executed_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )`);
  console.log('group_transfers table ready');

  await p.query(`
    CREATE TABLE IF NOT EXISTS group_eligibility_rules (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      group_name VARCHAR(30) NOT NULL UNIQUE,
      mandatory_subjects TEXT[] NOT NULL DEFAULT '{}',
      min_marks JSONB NOT NULL DEFAULT '{}',
      updated_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )`);

  const passRows = await p.query(`
    SELECT DISTINCT ON (name) name, pass_marks FROM subjects
     WHERE name ILIKE 'Math%' OR name ILIKE 'Science%' OR name ILIKE 'English%'
     ORDER BY name, class_id DESC`);
  const pm = {};
  for (const r of passRows.rows) pm[r.name] = Number(r.pass_marks || 33);
  const ruleSeeds = [
    ['Science', ['Math', 'Science', 'English'], pm],
    ['Commerce', ['Math', 'English'], pm],
    ['Arts', ['English'], pm],
  ];
  for (const [g, subs, mins] of ruleSeeds) {
    await p.query(
      `INSERT INTO group_eligibility_rules (group_name, mandatory_subjects, min_marks)
       VALUES ($1,$2,$3) ON CONFLICT (group_name) DO NOTHING`,
      [g, subs, JSON.stringify(mins)]
    );
  }
  console.log('group_eligibility_rules seeded:', ruleSeeds.length);

  // ------------------------------------------------------------------
  // 7) promotions — allocation columns
  // ------------------------------------------------------------------
  await addColumn('promotions', 'run_id', 'INTEGER REFERENCES promotion_runs(id) ON DELETE SET NULL');
  await addColumn('promotions', 'from_section', 'VARCHAR(30)');
  await addColumn('promotions', 'to_section', 'VARCHAR(30)');
  await addColumn('promotions', 'combined_rank', 'INTEGER');
  await addColumn('promotions', 'section_position', 'INTEGER');
  console.log('promotions columns ready');

  const check = await p.query(`
    SELECT table_name FROM information_schema.tables
     WHERE table_schema='public' AND table_name IN
       ('exam_catalog','mandatory_pass','promotion_runs','section_allocations',
        'group_selections','group_transfers','group_eligibility_rules')`);
  console.log('target tables present:', check.rows.length, '/ 7');
  process.exit(0);
})().catch(e => { console.log('FAIL:', e.message.split(String.fromCharCode(10))[0]); process.exit(1); });
