function mysqlToPgType(t) {
  t = String(t).toLowerCase();
  if (/^bigint/.test(t)) return 'BIGINT';
  if (/^(int|integer|mediumint)/.test(t)) return 'INTEGER';
  if (/^(tinyint|smallint)/.test(t)) return 'SMALLINT';
  if (/^varchar\(/.test(t)) return t.replace('varchar', 'VARCHAR');
  if (/^char\(/.test(t)) return t.replace('char', 'CHAR');
  if (/^(tiny|medium|long)?text/.test(t)) return 'TEXT';
  if (/^datetime/.test(t) || /^timestamp/.test(t)) return 'TIMESTAMPTZ';
  if (/^date\b/.test(t)) return 'DATE';
  if (/^time\b/.test(t)) return 'TIME';
  if (/^(decimal|numeric)/.test(t)) return t.replace('decimal', 'DECIMAL');
  if (/^double/.test(t)) return 'DOUBLE PRECISION';
  if (/^float/.test(t)) return 'REAL';
  if (/^enum/.test(t)) return 'TEXT';
  if (/^json/.test(t)) return 'JSONB';
  if (/^year/.test(t)) return 'INTEGER';
  return 'TEXT';
}

(async () => {
  const pg = new Pool({ connectionString: pgUrl, ssl: { rejectUnauthorized: false }, max: 5 });
  try {
    await pg.query("SET TIME ZONE 'UTC'");
    await pg.query('SET session_replication_role = replica'); // disable FK checks during bulk copy

    // widen legacy CHECK constraints so the real data values fit
    await pg.query('ALTER TABLE exams DROP CONSTRAINT IF EXISTS exams_exam_type_check');
    await pg.query("ALTER TABLE exams ADD CONSTRAINT exams_exam_type_check CHECK (exam_type IN ('class_test','midterm','final','test'))");
    await pg.query('ALTER TABLE notifications DROP CONSTRAINT IF EXISTS notifications_type_check');
    await pg.query("ALTER TABLE notifications ADD CONSTRAINT notifications_type_check CHECK (type IN ('attendance','result','general','notice','class_test_result','homework','complaint','special','promotion'))");

    // 1. list source tables
    const [myt, myf] = await my.query('SHOW TABLES');
    const tcol = myf[0].name;
    const myTables = myt.map(r => r[tcol]);

    // 2. create missing tables
    for (const ddl of NEW_TABLES) await pg.query(ddl);
    console.log('Created missing tables.');

    const pgTables = (await pg.query(
      "select table_name from information_schema.tables where table_schema='public'"))
      .rows.map(r => r.table_name);

    // 3. truncate ONLY tables we are about to refill (source tables that exist in PG)
    const toCopy = myTables.filter(t => pgTables.includes(t));
    for (const t of toCopy) {
      try { await pg.query(`TRUNCATE TABLE ${t} RESTART IDENTITY CASCADE`); }
      catch (e) { console.log('  truncate skip ' + t + ': ' + e.message); }
    }
    console.log('Truncated ' + toCopy.length + ' tables.');

    // 4. add columns the source has but PG lacks (tables are now empty -> NOT NULL safe)
    let added = 0;
    for (const t of toCopy) {
      const [mc] = await my.query('SHOW COLUMNS FROM `' + t + '`');
      const pgCols = (await pg.query(
        "select column_name from information_schema.columns where table_schema='public' and table_name=$1", [t]))
        .rows.map(r => r.column_name);
      for (const c of mc) {
        if (!pgCols.includes(c.Field)) {
          const type = mysqlToPgType(c.Type);
          const notNull = c.Null === 'NO';
          await pg.query(`ALTER TABLE ${t} ADD COLUMN IF NOT EXISTS "${c.Field}" ${type}${notNull ? ' NOT NULL' : ''}`);
          added++;
        }
      }
    }
    console.log('Added ' + added + ' missing columns.');

    // 5. copy rows (column intersection, IDs preserved) — batched multi-row inserts
    let total = 0;
    for (const t of toCopy) {
      const pgCols = (await pg.query(
        "select column_name from information_schema.columns where table_schema='public' and table_name=$1", [t]))
        .rows.map(r => r.column_name);
      const [rows] = await my.query('SELECT * FROM `' + t + '`');
      if (!rows.length) continue;
      const cols = Object.keys(rows[0]).filter(c => pgCols.includes(c));
      if (!cols.length) continue;
      const quoted = cols.map(c => '"' + c + '"').join(',');
      const nCols = cols.length;
      const chunk = Math.max(1, Math.floor(1000 / nCols));
      for (let i = 0; i < rows.length; i += chunk) {
        const slice = rows.slice(i, i + chunk);
        const valuesSql = [];
        const params = [];
        let p = 0;
        for (const r of slice) {
          valuesSql.push('(' + cols.map(() => '$' + (++p)).join(',') + ')');
          for (const c of cols) params.push(r[c] === undefined ? null : r[c]);
        }
        await pg.query(`INSERT INTO ${t} (${quoted}) VALUES ${valuesSql.join(',')}`, params);
      }
      total += rows.length;
      console.log('  ' + t + ': ' + rows.length);
    }
    console.log('Copied ' + total + ' rows total.');

    // 6. reset identity sequences to MAX(id)
    let seqs = 0;
    for (const t of toCopy) {
      try {
        const s = await pg.query("select pg_get_serial_sequence($1,'id') s", [t]);
        if (s.rows[0] && s.rows[0].s) {
          await pg.query('select setval($1, (select coalesce(max(id),1) from ' + t + '))', [s.rows[0].s]);
          seqs++;
        }
      } catch (e) { /* non-identity table */ }
    }
    console.log('Reset ' + seqs + ' sequences.');

    await pg.query('SET session_replication_role = origin');

    // 7. verification
    const checks = ['users', 'classes', 'students', 'subjects', 'routines',
      'routine_sections', 'routine_groups', 'time_slots', 'guardian_links', 'exams'];
    const out = [];
    for (const t of checks) {
      const r = await pg.query('SELECT count(*)::int n FROM ' + t);
      out.push(t + '=' + r.rows[0].n);
    }
    console.log('VERIFY: ' + out.join(' '));
    const liakat = await pg.query("SELECT id, username, name FROM users WHERE username='liakat'");
    console.log('liakat: ' + JSON.stringify(liakat.rows[0]));
    const nurul = await pg.query("SELECT id, username, name FROM users WHERE username='amin'");
    console.log('nurul/amin: ' + JSON.stringify(nurul.rows[0]));
    const cta = await pg.query(
      `SELECT c.name, c.section, c.group_name, u.name teacher FROM classes c JOIN users u ON u.id=c.teacher_id
       WHERE u.username IN ('liakat','amin') ORDER BY c.id`);
    console.log('their classes: ' + JSON.stringify(cta.rows));
  } catch (e) {
    console.error('MIGRATION FAILED:', e.message);
    try { await pg.query('SET session_replication_role = origin'); } catch (_) {}
    process.exitCode = 1;
  } finally {
    await pg.end();
    await my.end();
  }
})();
