const { Pool } = require('pg');
const p = new Pool({ connectionString: process.env.DATABASE_URL, ssl: process.env.DB_SSL !== 'false' });
(async () => {
  const q = async (t) => (await p.query(t)).rows;
  console.log('=== student_subjects cols ===');
  console.table((await q(`select column_name from information_schema.columns where table_name='student_subjects' order by ordinal_position`)));
  console.log('=== student_subjects count/sample ===');
  console.table((await q(`select count(*) from student_subjects`)));
  console.table(await q(`select * from student_subjects limit 20`));
  console.log('=== subject_aliases count ===');
  console.table(await q(`select count(*) from subject_aliases`));
  console.log('=== students by class ===');
  console.table(await q(`select c.id cid,c.name,c.section,c.group_name,count(s.id) st from classes c left join students s on s.class_id=c.id group by c.id order by c.id`));
  console.log('=== exams count + sample ===');
  console.table(await q(`select count(*) from exams`));
  console.table(await q(`select e.id,e.name,e.class_id,e.subject_id,s.name subj,s.class_id sclass,s.group_name from exams e left join subjects s on s.id=e.subject_id order by e.id limit 20`));
  console.log('=== routines count ===');
  console.table(await q(`select (select count(*) from routines) r,(select count(*) from routine_sections) rs,(select count(*) from routine_groups) rg`));
  console.log('=== class 1 subjects (full 13) ===');
  console.table(await q(`select id,name,sort_order from subjects where class_id=1 order by sort_order nulls last, id`));
  console.log('=== class 10 subjects (sample 16) ===');
  console.table(await q(`select id,name,group_name,is_optional,is_fourth_subject,is_elective from subjects where class_id=10 order by sort_order nulls last,id`));
  console.log('=== class 12 subjects (18) ===');
  console.table(await q(`select id,name,group_name,is_optional,is_fourth_subject,is_elective from subjects where class_id=12 order by sort_order nulls last,id`));
})().catch(e => { console.error(e.message); process.exit(1); }).finally(() => p.end());