require('dotenv').config({ quiet: true });
const { Pool } = require('pg');
const p = new Pool({ connectionString: process.env.DATABASE_URL, ssl: { rejectUnauthorized: false }, connectionTimeoutMillis: 15000 });
(async () => {
  // 1) New table: promotion decisions per (student, exam-event, term)
  await p.query(`
    CREATE TABLE IF NOT EXISTS promotions (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      student_id     INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
      event_id       INTEGER NOT NULL,
      class_id       INTEGER NOT NULL,
      group_name     VARCHAR(20),
      from_class     VARCHAR(50) NOT NULL,
      to_class       VARCHAR(50) NOT NULL,
      promoted_roll  INTEGER,
      decision       VARCHAR(30) NOT NULL DEFAULT 'promoted'
                     CHECK (decision IN ('promoted','retained','grace_promoted','admin_override')),
      final_gpa      NUMERIC(4,2) DEFAULT 0,
      recorded_by    INTEGER REFERENCES users(id) ON DELETE SET NULL,
      created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
      UNIQUE (student_id, event_id)
    )`);
  console.log('promotions table ready');

  // 2) New table: configurable promotion grace rules per class level
  await p.query(`
    CREATE TABLE IF NOT EXISTS promotion_grace (
      id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      class_id     INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
      exam_type    VARCHAR(20) NOT NULL DEFAULT 'test' ,
      grace_failed INTEGER NOT NULL DEFAULT 0,
      notes        VARCHAR(255),
      updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
      UNIQUE (class_id, exam_type)
    )`);
  console.log('promotion_grace table ready');

  // 3) Backfill one grace row for each existing class so review is deterministic
  const classes = [await p.query('SELECT id, name FROM classes')];
  for (const c of classes[0].rows) {
    await p.query(
      `INSERT INTO promotion_grace (class_id, exam_type, grace_failed, notes)
       VALUES ($1,'test',$2,$3)
       ON CONFLICT (class_id, exam_type) DO NOTHING`,
      [c.id, c.name.includes('Class 10') ? 2 : 0, 'default grace for ' + c.name]
    );
  }
  console.log('grace rows backfilled:', classes[0].rows.length);

  const ver = [await p.query(`SELECT column_name FROM information_schema.tables WHERE table_name IN ('promotions','promotion_grace')`)];
  console.log('target tables present:', ver[0].rows.length);
  process.exit(0);
})().catch(e => { console.log('FAIL:', e.message.split(String.fromCharCode(10))[0]); process.exit(1); });