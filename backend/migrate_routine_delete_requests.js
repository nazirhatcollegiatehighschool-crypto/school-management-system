const { Client } = require('pg');
require('dotenv').config();

const conn = process.env.DATABASE_URL;
if (!conn) { console.error('DATABASE_URL required'); process.exit(1); }

const ssl = process.env.DB_SSL !== 'false';

(async () => {
  const client = new Client({
    connectionString: conn,
    ssl: ssl ? { rejectUnauthorized: false } : false,
  });
  await client.connect();
  await client.query(`
    CREATE TABLE IF NOT EXISTS routine_delete_requests (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      routine_id INTEGER NOT NULL,
      teacher_id INTEGER NOT NULL,
      subject_name VARCHAR(150),
      class_details TEXT,
      day SMALLINT,
      time_slot_id INTEGER,
      reason TEXT,
      status TEXT NOT NULL DEFAULT 'pending',
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      decided_at TIMESTAMPTZ
    )
  `);
  const r = await client.query(
    `SELECT column_name FROM information_schema.columns
     WHERE table_name='routine_delete_requests' ORDER BY ordinal_position`
  );
  console.log('routine_delete_requests columns:', r.rows.map(c => c.column_name).join(', '));
  await client.end();
  console.log('OK');
})().catch(e => { console.error(e); process.exit(1); });